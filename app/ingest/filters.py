""" decide which files in repo are worth indexing """

from __future__ import annotations
from pathlib import PurePosixPath

EXCLUDED_DIRS = frozenset({
    ".git", ".hg", ".svn",
    "node_modules", "bower_components", "vendor", "third_party", "third-party", "bundled", "Pods",
    ".venv", "venv", "__pycache__", ".tox", ".mypy_cache", ".pytest_cache", ".ruff_cache",
    "dist", "build", "target", "out", "obj", ".next", ".nuxt", ".gradle", "coverage",
    ".idea", ".vscode", ".vs", ".cache",
})

LOCKFILES = frozenset({
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "npm-shrinkwrap.json",
    "poetry.lock", "uv.lock", "Pipfile.lock", "pdm.lock",
    "Cargo.lock", "go.sum", "composer.lock", "Gemfile.lock", "mix.lock", "flake.lock",
    "packages.lock.json", "Podfile.lock",
})

BINARY_EXTS = frozenset({
    # images / media
    ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".ico", ".icns", ".webp", ".tiff", ".psd",
    ".mp3", ".wav", ".ogg", ".flac", ".mp4", ".mov", ".avi", ".mkv", ".webm",
    # fonts
    ".ttf", ".otf", ".woff", ".woff2", ".eot",
    # archives
    ".zip", ".tar", ".gz", ".tgz", ".bz2", ".xz", ".7z", ".rar", ".jar", ".war", ".whl",
    # compiled / objects
    ".exe", ".dll", ".so", ".dylib", ".o", ".obj", ".a", ".lib", ".pdb", ".ilk",
    ".class", ".pyc", ".pyo", ".wasm", ".bin", ".dat",
    # documents / data blobs
    ".pdf", ".doc", ".docx", ".xls", ".xlsx", ".ppt", ".pptx",
    ".sqlite", ".db", ".npy", ".npz", ".pkl", ".parquet", ".onnx", ".pt", ".pth",
    ".safetensors", ".h5",
})

# Text, but data rather than code; large fixtures would eat the line budget.
DATA_EXTS = frozenset({".csv", ".tsv", ".jsonl", ".ndjson", ".log"})

MINIFIED_SUFFIXES = (".min.js", ".min.css", ".min.mjs", ".js.map", ".css.map")

_SNIFF_BYTES = 8192
_MINIFIED_AVG_LINE_LEN = 300
_GENERATED_MARKERS = (b"DO NOT EDIT", b"@generated", b"<auto-generated")

def skip_reason_for_path(rel: PurePosixPath)-> str |None:
    if any(part in EXCLUDED_DIRS for part in rel.parts[:-1]):
        return "excluded_dir"
    name = rel.name
    if name in LOCKFILES:
        return "lockfile"
    lower = name.lower()
    if lower.endswith(MINIFIED_SUFFIXES):
        return "minified"
    suffix = PurePosixPath(lower).suffix
    if suffix in BINARY_EXTS:
        return "binary"
    if suffix in DATA_EXTS:
        return "data_file"
    return None

DOC_EXTS = frozenset({".md", ".markdown", ".rst", ".txt", ".adoc", ".asciidoc", ".org"})
DOC_DIRS = frozenset({"docs", "doc", "documentation"})
TEST_DIRS = frozenset({"tests", "test", "__tests__", "spec", "specs"})
_TEST_NAME_PREFIXES = ("test_",)
_TEST_NAME_SUFFIXES = (
    "_test.py", "_test.go", "_test.rs", "_test.c", "_test.cc", "_test.cpp", "_spec.rb", "_test.rb",
    ".test.js", ".test.jsx", ".test.ts", ".test.tsx", ".test.mjs",
    ".spec.js", ".spec.jsx", ".spec.ts", ".spec.tsx",
    "test.java", "tests.java", "test.kt", "tests.kt", "tests.cs", "test.cs",
)

KINDS = ("code", "test", "docs")

def _is_doc_file(name: str)-> bool:
    if name == "cmakelists.txt" or (name.startswith(("requirements", "constraints")) and name.endswith(".txt")):
        return False
    return PurePosixPath(name).suffix in DOC_EXTS

def classify_kind(rel: PurePosixPath) -> str:
    """'docs' | 'test' | 'code'. Docs win over tests (a README inside tests/ is docs)."""
    dirs = {p.lower() for p in rel.parts[:-1]}
    name = rel.name.lower()
    if _is_doc_file(name) or dirs & DOC_DIRS:
        return "docs"
    if dirs & TEST_DIRS or name.startswith(_TEST_NAME_PREFIXES) or name.endswith(_TEST_NAME_SUFFIXES):
        return "test"
    return "code"

def count_lines(data: bytes) -> int:
    if not data:
        return 0
    return data.count(b"\n") + (0 if data.endswith(b"\n") else 1)


def skip_reason_for_content(data: bytes) -> str | None:
    """Call only on files that passed the path check. `data` is the full file."""
    if b"\x00" in data[:_SNIFF_BYTES]:
        return "binary"  # also catches UTF-16 files, which we don't support
    lines = count_lines(data)
    if lines and len(data) / lines > _MINIFIED_AVG_LINE_LEN:
        return "minified"
    head = data[:2048]
    if any(m in head for m in _GENERATED_MARKERS):
        return "generated"
    return None
